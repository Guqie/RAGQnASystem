import re

# 先抹掉否定说法，避免「不想死」被「想死」误伤。
_NEGATIVE = re.compile(r"不想死|不怕死|不要死|别去死|不会自杀|没有自杀")

_CRISIS = re.compile(
    "|".join(
        [
            r"自杀",
            r"轻生",
            r"不想活",
            r"活不下去",
            r"活着没意思",
            r"结束(自己的)?(生命|一生)",
            r"想死",
            r"去死",
            r"割腕",
            r"跳楼",
            r"烧炭",
            r"上吊",
            r"自残",
            r"伤害自己",
            r"不想活在",
        ]
    )
)

CRISIS_RESPONSE = """我很在意你刚才说的这些，也很感谢你愿意讲出来。你现在的痛苦是真实的，不需要一个人扛着。

如果你正在考虑伤害自己，或者觉得快撑不住了，请马上联系身边可信的人，并拨打紧急电话 110 或 120。你也可以打心理援助热线：

- 全国心理援助热线：12356
- 北京心理危机研究与干预中心：010-82951332
- 希望24热线：400-161-9995

这一轮我不会讨论用药，也不会做诊断。我可以继续陪你把此刻的感受说清楚。你现在是一个人，还是身边有可以联系的人？"""


def is_crisis(text: str) -> bool:
    if not text:
        return False
    cleaned = _NEGATIVE.sub("", text)
    return _CRISIS.search(cleaned) is not None
